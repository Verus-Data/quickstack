import { afterAll, describe, expect, it } from "vitest";
import { denyReason, makeFixture, REPO, runHook, write } from "../helpers/hooks";

const run = (filePath: string, env?: Record<string, string | undefined>) =>
  runHook("PreToolUse", "guard-tauri-generated", write(filePath, "x"), { env });

describe.concurrent("guard-tauri-generated denies", () => {
  it.each([
    [`${REPO}/src/core/generated/bindings.ts`, "generated by tauri-specta"],
    ["src/core/generated/bindings.ts", "generated by tauri-specta"],
    ["./src/core/generated/bindings.ts", "generated by tauri-specta"],
    [`${REPO}/.claude/worktrees/w/src/core/generated/bindings.ts`, "generated by tauri-specta"],
    [`${REPO}/src-tauri/gen/schemas/desktop-schema.json`, "generated by Tauri"],
    [`${REPO}/target/debug/build/out.rs`, "cargo build output"],
    [`${REPO}/Cargo.lock`, "Cargo.lock is written by cargo"],
  ])("%s", async (filePath, reason) => {
    expect(denyReason(await run(filePath))).toContain(reason);
  });

  it("falls back to the git root when CLAUDE_PROJECT_DIR is unset or missing", async () => {
    for (const dir of [undefined, "/does/not/exist"]) {
      const result = await run(`${REPO}/src/core/generated/bindings.ts`, {
        CLAUDE_PROJECT_DIR: dir,
      });
      expect(denyReason(result), String(dir)).toContain("generated by tauri-specta");
    }
  });
});

describe.concurrent("guard-tauri-generated allows", () => {
  it.each([
    `${REPO}/src/core/transport.ts`,
    `${REPO}/src/core/generated-helpers.ts`,
    `${REPO}/src-tauri/src/lib.rs`,
    `${REPO}/src-tauri/gen/android/app/build.gradle.kts`,
    `${REPO}/src-tauri/gen/apple/project.yml`,
    `${REPO}/src-tauri/Cargo.lock.md`,
    `${REPO}/crates/app-core/src/target/mod.rs`,
    "/somewhere/else/target/debug/out.rs",
  ])("%s", async (filePath) => {
    const result = await run(filePath);
    expect(result.code).toBe(0);
    expect(result.stdout).toBe("");
  });
});

describe("guard-tauri-generated with a project dir that isn't symlink-resolved", () => {
  const fixture = makeFixture();
  afterAll(fixture.cleanup);

  it("matches the symlink-resolved path too", async () => {
    const result = await run(`${fixture.real}/src/core/generated/bindings.ts`, {
      CLAUDE_PROJECT_DIR: fixture.dir,
    });
    expect(denyReason(result)).toContain("generated by tauri-specta");
  });
});
