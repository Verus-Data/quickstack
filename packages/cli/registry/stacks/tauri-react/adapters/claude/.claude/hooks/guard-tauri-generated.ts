// PreToolUse (Edit|Write): deny hand edits to files a tool generates. Editing them by hand is
// lost on the next run and hides the real fix.
//
//   src/core/generated/      tauri-specta bindings from the Rust commands and types (make bindings)
//   src-tauri/gen/schemas/   Tauri's generated capability schemas (any cargo build of the shell)
//   target/                  cargo build output
//   Cargo.lock               cargo's lockfile (cargo add / cargo remove / cargo update)
//
// src-tauri/gen/android and gen/apple are committed native projects; they stay editable.
import { realpathSync } from "node:fs";
import { isAbsolute, resolve } from "node:path";
import { deny, projectRoot, readPayload, text } from "./_lib";

function physical(dir: string): string {
  try {
    return realpathSync(dir);
  } catch {
    return dir;
  }
}

/** The path relative to the project root, or to a worktree under .claude/worktrees/. */
function relPath(filePath: string): string | undefined {
  // The root as given and with symlinks resolved (/tmp vs /private/tmp), each without a trailing
  // slash, so neither can route a generated file around the guard.
  const given = projectRoot().replace(/\/+$/, "");
  const abs = isAbsolute(filePath) ? filePath : resolve(given, filePath);
  const root = [given, physical(given || "/").replace(/\/+$/, "")].find((d) =>
    abs.startsWith(`${d}/`),
  );
  if (root === undefined) return undefined;
  return abs.slice(root.length + 1).replace(/^\.claude\/worktrees\/[^/]+\//, "");
}

function reasonFor(rel: string): string | undefined {
  if (rel.startsWith("src/core/generated/")) {
    return `${rel} is generated by tauri-specta from the Rust commands and types. Change the Rust side (derive specta::Type, register the command or event with the builder), then run make bindings. Don't hand-write a TypeScript mirror of a Rust type either.`;
  }
  if (rel.startsWith("src-tauri/gen/schemas/")) {
    return `${rel} is generated by Tauri. Change src-tauri/capabilities/ or tauri.conf.json and rebuild.`;
  }
  if (rel.startsWith("target/")) {
    return `${rel} is cargo build output. Change the source and rebuild.`;
  }
  if (rel === "Cargo.lock") {
    return "Cargo.lock is written by cargo. Change a Cargo.toml with cargo add / cargo remove, or run cargo update.";
  }
  return undefined;
}

const filePath = text(readPayload()?.tool_input?.file_path);
const rel = filePath ? relPath(filePath) : undefined;
const reason = rel ? reasonFor(rel) : undefined;
if (reason) deny(`BLOCKED: ${reason}`);
