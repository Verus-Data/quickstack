import { describe, expect, it } from "vitest";
import { denyReason, REPO, runHook, write } from "../helpers/hooks";

const run = (path: string) =>
  runHook("PreToolUse", "guard-nextjs-generated", write(path, "export {};\n"));

describe.concurrent("guard-nextjs-generated denies", () => {
  it.each([
    [`${REPO}/.next/types/routes.d.ts`, "is generated by Next"],
    [".next/server/app/page.js", "is generated by Next"],
    [`${REPO}/next-env.d.ts`, "next-env.d.ts is written by Next"],
    [`${REPO}/test-results/items/error-context.md`, "is Playwright output"],
    [`${REPO}/playwright-report/index.html`, "is Playwright output"],
  ])("%s", async (path, reason) => {
    expect(denyReason(await run(path))).toContain(reason);
  });
});

describe.concurrent("guard-nextjs-generated allows", () => {
  it.each([
    `${REPO}/src/app/page.tsx`,
    `${REPO}/src/types/next-extra.d.ts`,
    `${REPO}/next.config.ts`,
    `${REPO}/e2e/items.spec.ts`,
    "/somewhere/else/.next/types/routes.d.ts",
  ])("%s", async (path) => {
    const result = await run(path);
    expect(result.code).toBe(0);
    expect(result.stdout).toBe("");
  });
});
