// PreToolUse (Edit|Write): deny hand edits to files Next and the test tools generate. Editing
// them by hand is lost on the next run and hides the real fix. The shared guard-generated hook
// already covers build/, dist/, coverage/ and bun.lock.
//
//   .next/                 build output and generated route types (bun run build, bun run typecheck)
//   next-env.d.ts          Next's type reference file (written by next dev and next build)
//   test-results/          Playwright failure output (bun run e2e)
//   playwright-report/     Playwright HTML report (bun run e2e)
import { spawnSync } from "node:child_process";
import { realpathSync } from "node:fs";
import { deny, readPayload, text } from "./_lib";

function root(): string {
  if (process.env.CLAUDE_PROJECT_DIR) return process.env.CLAUDE_PROJECT_DIR;
  const git = spawnSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" });
  return git.status === 0 ? git.stdout.trim() : process.cwd();
}

function physical(dir: string): string {
  try {
    return realpathSync(dir);
  } catch {
    return dir;
  }
}

function reasonFor(filePath: string): string | undefined {
  // The root as given and with symlinks resolved (/tmp vs /private/tmp), each without a trailing
  // slash, so neither can route a generated file around the guard.
  const given = root().replace(/\/+$/, "");
  const dirs = [given, physical(given || "/").replace(/\/+$/, "")];
  const dir = dirs.find((d) => filePath.startsWith(`${d}/`));
  let rel = filePath;
  if (dir !== undefined) rel = filePath.slice(dir.length + 1);
  else if (filePath.startsWith("/")) return undefined;

  if (rel.startsWith(".next/")) {
    return `${rel} is generated by Next. Change the source or next.config, then run bun run build or bun run typecheck.`;
  }
  if (rel === "next-env.d.ts") {
    return "next-env.d.ts is written by Next on dev and build. Put custom type declarations in a separate .d.ts file.";
  }
  if (rel.startsWith("test-results/") || rel.startsWith("playwright-report/")) {
    return `${rel} is Playwright output. Change the spec or the app and run bun run e2e.`;
  }
  return undefined;
}

const filePath = text(readPayload()?.tool_input?.file_path);
const reason = filePath ? reasonFor(filePath) : undefined;
if (reason) deny(`BLOCKED: ${reason}`);
