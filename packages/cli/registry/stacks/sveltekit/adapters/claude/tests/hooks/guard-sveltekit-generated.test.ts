import { describe, expect, it } from "vitest";
import { denyReason, REPO, runHook, write } from "../helpers/hooks";

const run = (path: string) =>
  runHook("PreToolUse", "guard-sveltekit-generated", write(path, "export {};\n"));

describe.concurrent("guard-sveltekit-generated denies", () => {
  it.each([
    [`${REPO}/.svelte-kit/types/src/routes/$types.d.ts`, "is generated by SvelteKit"],
    [`${REPO}/.svelte-kit/tsconfig.json`, "is generated by SvelteKit"],
    [".svelte-kit/output/server/index.js", "is generated by SvelteKit"],
    [`${REPO}/test-results/items/error-context.md`, "is Playwright output"],
    [`${REPO}/playwright-report/index.html`, "is Playwright output"],
  ])("%s", async (path, reason) => {
    expect(denyReason(await run(path))).toContain(reason);
  });
});

describe.concurrent("guard-sveltekit-generated allows", () => {
  it.each([
    `${REPO}/src/routes/+page.svelte`,
    `${REPO}/src/app.d.ts`,
    `${REPO}/tsconfig.json`,
    `${REPO}/vite.config.ts`,
    `${REPO}/e2e/items.spec.ts`,
    "/somewhere/else/.svelte-kit/tsconfig.json",
  ])("%s", async (path) => {
    const result = await run(path);
    expect(result.code).toBe(0);
    expect(result.stdout).toBe("");
  });
});
